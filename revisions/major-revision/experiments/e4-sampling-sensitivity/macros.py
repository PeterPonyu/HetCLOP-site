"""Write LaTeX macros for the E4 numbers quoted in the manuscript.

Every value is read from summary.csv, composition-summary.csv or the per-fit
group tables; nothing is typed by hand.
"""
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
OUT = HERE.parents[1] / 'manuscript' / 'figs' / 'e4_numbers.tex'
s = pd.read_csv(HERE / 'summary.csv')
c = pd.read_csv(HERE / 'composition-summary.csv', index_col=0)
comp = pd.read_csv(HERE / 'composition.csv')
g = pd.concat([pd.read_csv(p) for p in sorted((HERE / 'runs').glob('*/groups.csv'))], ignore_index=True)

m = {}
def put(name, value, fmt='{:.3f}'):
    m[name] = fmt.format(value) if not isinstance(value, str) else value

variants = list(dict.fromkeys(s.variant))
alt = [v for v in variants if v != 'reference']
put('EfourNvariants', len(alt), '{:d}')
put('EfourNstable', int(s[s.variant != 'reference'].stable.sum()), '{:d}')
put('EfourNcomparisons', int((s.variant != 'reference').sum()), '{:d}')

def rng(contrast, prefix, digits=3):
    sub = s[s.contrast == contrast]
    ref = sub[sub.variant == 'reference'].iloc[0]
    put(prefix + 'Ref', ref.effect, f'{{:.{digits}f}}')
    put(prefix + 'RefLo', ref.ci_low, f'{{:.{digits}f}}')
    put(prefix + 'RefHi', ref.ci_high, f'{{:.{digits}f}}')
    put(prefix + 'Min', sub.effect.min(), f'{{:.{digits}f}}')
    put(prefix + 'Max', sub.effect.max(), f'{{:.{digits}f}}')
    put(prefix + 'Class', ref.classification)
    put(prefix + 'Stable', int(sub.stable.sum()), '{:d}')

rng('Arm A per-cell minus Poisson calibration error', 'EfourACal')
rng('Arm B per-cell minus Poisson calibration error', 'EfourBCal')
rng('Arm B per-cell minus shared calibration error', 'EfourBAlloc')
rng('Arm B per-cell minus Poisson Welch recall', 'EfourBWelch')
rng('Arm B per-cell minus shared Welch recall', 'EfourBWelchAlloc')
rng('Deficit-effect slope (pooled arms)', 'EfourSlope')

# Group-level Poisson-win fraction for the Arm A calibration contrast, per variant.
a = g[g.arm == 'A'].assign(d=lambda x: x.cal_cell - x.cal_poisson).groupby(['variant', 'dataset', 'cell_type']).d.mean()
win = (a > 0).groupby('variant').mean() * 100
put('EfourAWinRef', win['reference'], '{:.1f}')
put('EfourAWinMin', win.min(), '{:.1f}')
put('EfourAWinMax', win.max(), '{:.1f}')

# Composition: cells, scored groups, rare types, batches, transfer share.
put('EfourCellsCap', int(c.loc['cap10000', 'cells']), '{:,}')
put('EfourGroupsRef', int(c.loc['reference', 'scored_groups']), '{:d}')
put('EfourGroupsCap', int(c.loc['cap10000', 'scored_groups']), '{:d}')
put('EfourGroupsFloor', int(c.loc['type_floor', 'scored_groups']), '{:d}')
put('EfourBatchDatasets', int((comp[(comp.variant == 'batch_balanced') & ~comp.excluded].batch_fallback == False).sum()), '{:d}')
put('EfourTransferUniform', 100 * c.loc[['uniform_s1', 'uniform_s2', 'uniform_s3'], 'transferred_share'].mean(), '{:.0f}')
put('EfourMadCells', int(c.loc['mad_qc', 'cells']), '{:,}')

lines = ['% E4 sampling and quality-control sensitivity; generated by experiments/e4-sampling-sensitivity/macros.py']
for k, v in m.items():
    lines.append(f'\\newcommand{{\\{k}}}{{{v}}}')
OUT.write_text('\n'.join(lines) + '\n')
print('\n'.join(lines))

# Post-hoc restriction of the 10,000-cell variant to the reference groups (labelled post hoc in the text).
ph = pd.read_csv(HERE / 'posthoc-common-groups.csv')
extra = {}
for key, contrast in [('EfourPhBCal', 'Arm B per-cell minus Poisson calibration error'),
                      ('EfourPhBWelch', 'Arm B per-cell minus Poisson Welch recall')]:
    r = ph[(ph.variant == 'cap10000') & (ph.contrast == contrast)].iloc[0]
    extra[key], extra[key + 'Lo'], extra[key + 'Hi'] = (f'{x:.4f}' if abs(x) < 5e-4 else f'{x:.3f}' for x in (r.effect, r.ci_low, r.ci_high))
# Values for the 10,000-cell variant itself.
for key, contrast in [('EfourCapBCal', 'Arm B per-cell minus Poisson calibration error'),
                      ('EfourCapBWelch', 'Arm B per-cell minus Poisson Welch recall'),
                      ('EfourCapSlope', 'Deficit-effect slope (pooled arms)'),
                      ('EfourFloorBCal', 'Arm B per-cell minus Poisson calibration error')]:
    v = 'type_floor' if key.startswith('EfourFloor') else 'cap10000'
    r = s[(s.variant == v) & (s.contrast == contrast)].iloc[0]
    extra[key], extra[key + 'Lo'], extra[key + 'Hi'] = (f'{x:.4f}' if abs(x) < 5e-4 else f'{x:.3f}' for x in (r.effect, r.ci_low, r.ci_high))
with OUT.open('a') as f:
    for k, v in extra.items():
        f.write(f'\\newcommand{{\\{k}}}{{{v}}}\n')
print(extra)
