"""Three-refit summaries of the frozen-mean scVI allocation probe, read from the saved probe results."""
import json
from pathlib import Path
import numpy as np
R = Path(__file__).resolve().parents[3]
p = json.load(open(R / 'experiments/phase2j_external_2026-07-09/results/scvi_theta_probe.json'))['results']
seeds = sorted(p)
def c(name, key): return [p[s]['contrasts'][name][key] for s in seeds]
def d(arm, key): return [p[s]['direction'][arm][key] for s in seeds]
m = {}
m['ProbeRefitPoisSigned'] = f"{np.mean(d('poisson_on_mean','r_var_signed_expr_median')):.3f}"
m['ProbeRefitGlobSigned'] = f"{np.mean(d('nb_global_theta','r_var_signed_expr_median')):.3f}"
m['ProbeRefitAmortSigned'] = f"{np.mean(d('nb_amortized','r_var_signed_expr_median')):.3f}"
m['ProbeRefitGlobLossRvar'] = f"{100*np.mean(c('nb_global_vs_poisson__rvar_expressed','b_win_fraction_groups')):.1f}"
m['ProbeRefitGlobLossEnergy'] = f"{100*np.mean(c('nb_global_vs_poisson__energy','b_win_fraction_groups')):.1f}"
m['ProbeRefitGlobPmax'] = f"{max(c('nb_global_vs_poisson__rvar_expressed','clustered_wilcoxon_p') + c('nb_global_vs_poisson__energy','clustered_wilcoxon_p')):.2e}"
m['ProbeRefitAmortWinEnergy'] = f"{100*np.mean([1-x for x in c('nb_amortized_vs_poisson__energy','b_win_fraction_groups')]):.1f}"
m['ProbeRefitAmortVsGlobWin'] = f"{100*np.mean([1-x for x in c('nb_amortized_vs_nb_global__energy','b_win_fraction_groups')]):.1f}"
m['ProbeRefitAmortVsGlobPmax'] = f"{max(c('nb_amortized_vs_nb_global__energy','clustered_wilcoxon_p')):.2e}"
out = R / 'revisions/major-revision/manuscript/figs/probe_refit_numbers.tex'
out.write_text('% Three-refit summaries of the scVI frozen-mean probe; generated by evidence/probe_three_refit_macros.py\n' +
               ''.join(f'\\newcommand{{\\{k}}}{{{v}}}\n' for k, v in m.items()))
print(m)
