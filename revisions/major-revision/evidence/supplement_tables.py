"""Supplementary Tables S2-S4, generated from saved outputs (Table S1 comes from
experiments/e4-sampling-sensitivity/supplement_composition.py). Nothing is typed by hand."""
import re
from pathlib import Path

import pandas as pd

REV = Path(__file__).resolve().parents[1]
EXP = REV / 'experiments'
FIGS = REV / 'manuscript' / 'figs'


def accession_labels():
    dt = pd.read_csv(FIGS / 'dataset_table.csv')
    tex = (FIGS / 'tab_datasets.tex').read_text()
    out = {}
    for acc, sup, n, t in re.findall(r'(GSE\d+)(?:\$\^\{\\mathrm\{([ab])\}\}\$)? & (?:Mm|Hs) & (\d+) & (\d+)', tex):
        hit = dt[(dt.accession == acc) & (dt.n_cells == int(n)) & (dt.n_cell_types == int(t))]
        out[hit.dataset_id.iloc[0]] = acc + (f'$^{{\\mathrm{{{sup}}}}}$' if sup else '')
    return dict(sorted(out.items(), key=lambda kv: (int(re.match(r'GSE(\d+)', kv[1]).group(1)), kv[1])))


def num(x, digits=3):
    # A nonzero value that would round to zero gets extra digits, so no limit prints as a false 0.000.
    d = digits
    while x != 0 and abs(x) < 0.5 * 10 ** -d and d < digits + 3:
        d += 1
    return f'{x:.{d}f}'


def f3(x):
    return num(x, 3)


def table_transfer():
    d = pd.read_csv(EXP / 'e4c-label-transfer' / 'datasets.csv').set_index('dataset')
    t = pd.read_csv(EXP / 'e4c-label-transfer' / 'types.csv')
    rare = t[t.rare].groupby('dataset').recall.mean()
    acc = accession_labels()
    rows = []
    for ds, lab in acc.items():
        r = d.loc[ds]
        rows.append([lab, f'{int(r.n_labelled):,}', str(int(r.n_types)), f3(r.coverage), f3(r.accuracy_assigned),
                     f3(r.macro_f1), str(int(r.n_rare_types)), f3(rare[ds]) if ds in rare.index else '--'])
    half = (len(rows) + 1) // 2
    lines = ['% AUTO-GENERATED by evidence/supplement_tables.py; do not edit.', '{\\scriptsize', '\\setlength{\\tabcolsep}{2.6pt}',
             '\\begin{tabular}{@{}lrrrrrrr@{\\hspace{1.2em}}lrrrrrrr@{}}', '\\toprule',
             ' & Cells & T & Cov. & Acc. & F1 & R & Rec. & & Cells & T & Cov. & Acc. & F1 & R & Rec.\\\\', '\\midrule']
    for i in range(half):
        right = rows[half + i] if half + i < len(rows) else [''] * 8
        lines.append(' & '.join(rows[i] + right) + '\\\\')
    lines += ['\\bottomrule', '\\end{tabular}', '}']
    (FIGS / 'tab_s2_transfer.tex').write_text('\n'.join(lines) + '\n')


def table_selection():
    s = pd.read_csv(EXP / 'e3-prospective-selection' / 'summary.csv')
    names = {'pca_512': 'PCA-512', 'randproj_512': 'Random projection-512', 'scgpt_512': 'scGPT-512', 'geneformer': 'Geneformer',
             'all encoders': 'All encoders'}
    def get(arm, scope, q):
        return s[(s.arm == arm) & (s.scope == scope) & (s.quantity == q)].iloc[0]
    def ci(arm, scope, q):
        r = get(arm, scope, q)
        return f'\\shortstack{{${num(r.effect)}$\\\\$[{num(r.ci_low)},{num(r.ci_high)}]$}}'
    lines = ['% AUTO-GENERATED by evidence/supplement_tables.py; do not edit.', '{\\scriptsize', '\\setlength{\\tabcolsep}{3.5pt}',
             '\\begin{tabular}{@{}llrrrrccc@{}}', '\\toprule',
             ' & & \\multicolumn{4}{c}{Chosen option (\\%)} & & \\multicolumn{2}{c}{Selected minus always}\\\\',
             '\\cmidrule(lr){3-6}\\cmidrule(l){8-9}',
             'Arm & Encoder & Pois. & Shared & Type & Cell & Regret & Poisson & per-cell\\\\', '\\midrule']
    for arm in ['A', 'B']:
        for scope in ['pca_512', 'randproj_512', 'scgpt_512', 'geneformer', 'all encoders']:
            freq = [f'{100 * get(arm, scope, f"chosen_{o}").effect:.0f}' for o in ['poisson', 'shared', 'per_type', 'per_cell']]
            lines.append(' & '.join([arm, names[scope]] + freq + [ci(arm, scope, 'regret'), ci(arm, scope, 'vs_poisson'),
                                                                  ci(arm, scope, 'vs_per_cell')]) + '\\\\[2pt]')
        if arm == 'A':
            lines.append('\\midrule')
    lines += ['\\bottomrule', '\\end{tabular}', '}']
    (FIGS / 'tab_s3_selection.tex').write_text('\n'.join(lines) + '\n')


def table_accession():
    a = pd.read_csv(EXP / 'e7-accession-clustering' / 'accession-summary.csv')
    keep = [
        ('e2_slope', 'deficit-effect slope, pooled', 'Deficit--effect slope, pooled'),
        ('e2_slope', 'deficit-effect slope, Arm_A', 'Deficit--effect slope, Arm A'),
        ('e2_slope', 'deficit-effect slope, Arm_B', 'Deficit--effect slope, Arm B'),
        ('e1_matched', 'Arm A per_cell minus poisson: calibration', 'Matched, Arm A: per-cell $-$ Poisson calibration'),
        ('e1_matched', 'Arm B per_cell minus poisson: calibration', 'Matched, Arm B: per-cell $-$ Poisson calibration'),
        ('e1_matched', 'Arm B per_cell minus poisson: welch', 'Matched, Arm B: per-cell $-$ Poisson Welch recall'),
        ('e1_matched', 'Arm B per_cell minus poisson: rare_f1_full', 'Matched, Arm B: per-cell $-$ Poisson rare-type F1'),
        ('e1_matched', 'Arm B per_cell minus shared_per_gene: welch', 'Matched, Arm B: per-cell $-$ shared Welch recall'),
        ('e4_reference', 'Arm A per-cell minus Poisson calibration error', 'Reference corpus, Arm A: per-cell $-$ Poisson calibration'),
        ('e4_reference', 'Arm B per-cell minus shared calibration error', 'Reference corpus, Arm B: per-cell $-$ shared calibration'),
        ('e4_scvi_reference', 'scVI shared per-gene NB minus Poisson calibration error', 'scVI: shared $-$ Poisson calibration'),
        ('e4_scvi_reference', 'scVI per-cell NB minus Poisson calibration error', 'scVI: per-cell $-$ Poisson calibration'),
        ('e3_selection', 'Arm A regret relative to the best option on test', 'Selection, Arm A: regret'),
        ('e3_selection', 'Arm B selected minus always-Poisson', 'Selection, Arm B: selected $-$ always Poisson'),
        ('e6_dependence', 'Arm A cell minus poisson correlation error', 'Dependence, Arm A: per-cell $-$ Poisson'),
        ('e6_dependence', 'Arm B cell minus poisson correlation error', 'Dependence, Arm B: per-cell $-$ Poisson'),
    ]
    def cell(r, digits):
        return f'${num(r.effect, digits)}$ $[{num(r.ci_low, digits)},{num(r.ci_high, digits)}]$'

    # The dataset-cluster column repeats each analysis's own reported interval, so an estimate carries one interval
    # throughout the paper; the accession check recomputed the dataset-unit values with its own stream, and only its
    # point estimates are compared here.
    sv = pd.read_csv(EXP / 'e4-scvi-sensitivity' / 'summary.csv')
    e3 = pd.read_csv(EXP / 'e3-prospective-selection' / 'summary.csv')
    e6 = pd.read_csv(EXP / 'e6-gene-dependence' / 'summary.csv')
    def primary(an, ct, d):
        if an == 'e4_scvi_reference':
            mode = 'gene' if 'shared' in ct else 'gene-cell'
            r = sv[(sv.variant == 'reference') & (sv['mode'] == mode)].iloc[0]
        elif an == 'e3_selection':
            arm = ct.split()[1]
            q = 'regret' if 'regret' in ct else ('vs_poisson' if 'Poisson' in ct else 'vs_per_cell')
            r = e3[(e3.arm == arm) & (e3.scope == 'all encoders') & (e3.quantity == q)].iloc[0]
        elif an == 'e6_dependence':
            arm, a_, _, b_ = ct.split()[1], ct.split()[2], None, ct.split()[4]
            r = e6[(e6.arm == arm) & (e6.metric == 'corr') & (e6.a == a_) & (e6.b == b_)].iloc[0]
        else:
            return d
        assert abs(r.effect - d.effect) < 1e-9, (an, ct, r.effect, d.effect)
        return r
    lines = ['% AUTO-GENERATED by evidence/supplement_tables.py; do not edit.', '{\\scriptsize', '\\setlength{\\tabcolsep}{4pt}',
             '\\begin{tabular}{@{}lll@{}}', '\\toprule', 'Contrast & Datasets (50 clusters) & Accessions (45 clusters)\\\\', '\\midrule']
    for an, ct, label in keep:
        d = primary(an, ct, a[(a.analysis == an) & (a.contrast == ct) & (a.unit == 'dataset')].iloc[0])
        x = a[(a.analysis == an) & (a.contrast == ct) & (a.unit == 'accession')].iloc[0]
        digits = 4 if 'slope' not in ct and max(abs(d.ci_low), abs(d.ci_high)) < 0.02 else 3
        lines.append(f'{label} & {cell(d, digits)} & {cell(x, digits)}\\\\')
    en = a[a.analysis == 'armb_energy']
    lines.append('\\midrule')
    for enc, name in [('pca_512', 'PCA-512'), ('randproj_512', 'random projection-512'), ('scgpt_512', 'scGPT-512'), ('geneformer', 'Geneformer')]:
        d = en[(en.contrast.str.endswith(enc)) & (en.unit == 'dataset')].iloc[0]
        x = en[(en.contrast.str.endswith(enc)) & (en.unit == 'accession')].iloc[0]
        lines.append(f'Arm B energy, {name}: largest Wilcoxon $p$ & \\num{{{d.wilcoxon_p_worst:.2e}}} & \\num{{{x.wilcoxon_p_worst:.2e}}}\\\\')
    lines += ['\\bottomrule', '\\end{tabular}', '}']
    (FIGS / 'tab_s4_accession.tex').write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    table_transfer()
